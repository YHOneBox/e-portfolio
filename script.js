function setupNotice() {
    const notice = document.getElementById("update-notice");
    const closeBtn = document.getElementById("update-notice-close");
    const key = "updateNoticeDismissed";
    if (!notice) return;

    if (sessionStorage.getItem(key) === "1") {
        notice.classList.add("is-hidden");
    } else {
        document.body.classList.add("has-update-notice");
    }

    closeBtn?.addEventListener("click", () => {
        notice.classList.add("is-hidden");
        document.body.classList.remove("has-update-notice");
        sessionStorage.setItem(key, "1");
    });
}

function setupTheme() {
    const root = document.documentElement;
    const toggle = document.getElementById("theme-toggle");
    if (!root.dataset.theme) {
        const stored = localStorage.getItem("theme");
        const prefersLight = window.matchMedia("(prefers-color-scheme: light)").matches;
        root.dataset.theme = stored || (prefersLight ? "light" : "dark");
    }

    toggle?.addEventListener("click", () => {
        const next = root.dataset.theme === "light" ? "dark" : "light";
        root.dataset.theme = next;
        localStorage.setItem("theme", next);
        applyI18n();
    });
}

function setupLang() {
    document.querySelectorAll("[data-lang-set]").forEach((btn) => {
        btn.addEventListener("click", () => setLang(btn.dataset.langSet));
    });
}

function setupNav() {
    const toggle = document.getElementById("menu-toggle");
    const nav = document.getElementById("site-nav");
    const links = nav?.querySelectorAll("a") ?? [];

    const close = () => {
        nav?.classList.remove("is-open");
        toggle?.setAttribute("aria-expanded", "false");
        toggle?.setAttribute("aria-label", t("openMenu"));
    };

    toggle?.addEventListener("click", () => {
        const open = !nav?.classList.contains("is-open");
        nav?.classList.toggle("is-open", open);
        toggle.setAttribute("aria-expanded", String(open));
        toggle.setAttribute("aria-label", open ? t("closeMenu") : t("openMenu"));
    });

    links.forEach((link) => link.addEventListener("click", () => close()));
    document.addEventListener("keydown", (event) => {
        if (event.key === "Escape") close();
    });
}

function setupScrollSpy() {
    const sections = ["about", "projects", "resume", "contact"]
        .map((id) => document.getElementById(id))
        .filter(Boolean);
    const links = [...document.querySelectorAll(".nav-list a")];

    const observer = new IntersectionObserver((entries) => {
        entries.forEach((entry) => {
            if (!entry.isIntersecting) return;
            links.forEach((link) => {
                const active = link.getAttribute("href") === `#${entry.target.id}`;
                if (active) link.setAttribute("aria-current", "page");
                else link.removeAttribute("aria-current");
            });
        });
    }, { rootMargin: "-45% 0px -45% 0px" });

    sections.forEach((section) => observer.observe(section));
}

